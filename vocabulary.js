  const matchers = entries.map(([term, meaning, weight]) => {
    const escaped = term.replace(/[.*+?^${}()|[\]\\]/g, '\\$&').replace(/\s+/g, '\\s+');
    return { term, meaning, weight, pattern: new RegExp(`(^|[^a-z])${escaped}(?:s|es)?(?=$|[^a-z])`, 'i') };
  });

  function find(prompt, options, limit = 10) {
    const promptMatches = matchers.filter(entry => entry.pattern.test(prompt));
    const optionMatches = matchers.filter(entry => !entry.pattern.test(prompt) && entry.pattern.test(options));
    const sort = (a, b) => b.weight - a.weight || b.term.length - a.term.length;
    promptMatches.sort(sort);
    optionMatches.sort(sort);
    const chosen = [...promptMatches.slice(0, 6), ...optionMatches.slice(0, 4)];
    const seen = new Set(chosen.map(entry => entry.term));
    for (const entry of [...promptMatches.slice(6), ...optionMatches.slice(4)]) {
      if (chosen.length >= limit) break;
      if (!seen.has(entry.term)) { chosen.push(entry); seen.add(entry.term); }
    }
    return chosen.slice(0, limit).map(({ term, meaning }) => ({ term, meaning }));
  }

  function intent(prompt, correctCount) {
    if (/\b(most likely cause|most likely reason|why (?:did|does|is|was)|root cause)\b/i.test(prompt)) return 'Câu hỏi yêu cầu tìm nguyên nhân hợp lý nhất của tình huống.';
    if (/\b(first|initial|before anything else)\b/i.test(prompt) && /\b(step|action|do|should)\b/i.test(prompt)) return 'Câu hỏi yêu cầu xác định bước nên làm đầu tiên.';
    if (/\b(which two|choose two|select two|which three|choose three|select three)\b/i.test(prompt)) return `Câu hỏi yêu cầu chọn ${correctCount} phương án đúng; cần xét từng lựa chọn độc lập.`;
    if (/\b(which|what)\b.{0,40}\bapproach\b.{0,30}\bappropriate\b/i.test(prompt)) return 'Câu hỏi yêu cầu chọn cách thiết kế phù hợp nhất với quy trình đã mô tả.';
    if (/\b(most effective|best approach|most appropriate|best way)\b/i.test(prompt)) return 'Câu hỏi yêu cầu chọn cách làm phù hợp và hiệu quả nhất trong bối cảnh đã nêu.';
    if (/\b(correct order|sequence|in what order)\b/i.test(prompt)) return 'Câu hỏi yêu cầu sắp xếp các bước theo đúng trình tự.';
    if (/\b(what should|how should|which approach|what is the best)\b/i.test(prompt)) return 'Câu hỏi yêu cầu chọn hành động hoặc phương án phù hợp với tình huống.';
    return 'Đọc bối cảnh trước, sau đó đối chiếu từng lựa chọn với yêu cầu ở cuối câu hỏi.';
  }

  const api = { entries, find, intent };
